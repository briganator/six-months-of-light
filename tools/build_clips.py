"""Quote video clips (prototype). For each curated quote: download the official talk audio/video
(ChurchofJesusChrist.org, from assets/fulltext/<id>.json) to /workspace/scratch/clips, transcribe with
faster-whisper (word timestamps; the Church media has no public timed captions in our data), find where the
quote is spoken by fuzzy word alignment, cut it with padding, and write assets/clips/<id>-q<n>.mp4 plus
assets/clips.js (timings + per-word captions relative to the clip).
Run: /workspace/.venv-cv/bin/python tools/build_clips.py"""
import json, os, re, subprocess, urllib.request, difflib, unicodedata
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__))); SCR='/workspace/scratch/clips'; os.makedirs(SCR,exist_ok=True)
OUT=os.path.join(ROOT,'assets','clips'); os.makedirs(OUT,exist_ok=True)
CLIPS=[('sat-pm-7-kearon',0),('sat-am-2-runia',2),('sat-am-3-causse',0),('sun-pm-4-bednar',1)]
PAD0,PAD1=0.45,0.7
s=open(os.path.join(ROOT,'assets','data.js')).read(); D=json.loads(s[s.index('{'):s.rstrip().rstrip(';').rindex('}')+1]); T={t['id']:t for t in D['talks']}
norm=lambda w: re.sub(r'[^a-z0-9]','',unicodedata.normalize('NFD',w.lower()).replace('’',"'"))
def dl(u,p):
    if not os.path.exists(p): urllib.request.urlretrieve(u,p)
model=None; out={}
for tid,qi in CLIPS:
    ft=json.load(open(os.path.join(ROOT,'assets','fulltext',tid+'.json'))); v=ft['video']['src'] if isinstance(ft['video'],dict) else ft['video']
    mp3=f'{SCR}/{tid}.mp3'; mp4=f'{SCR}/{tid}.mp4'; dl(ft['audio'],mp3); dl(v,mp4)
    wj=f'{SCR}/{tid}.words.json'
    if not os.path.exists(wj):
        if model is None:
            from faster_whisper import WhisperModel; model=WhisperModel('small.en',device='cpu',compute_type='int8')
        import numpy as np
        pcm=subprocess.run(['ffmpeg','-loglevel','error','-i',mp3,'-f','f32le','-ac','1','-ar','16000','-'],capture_output=True,check=True).stdout
        segs,_=model.transcribe(np.frombuffer(pcm,np.float32),word_timestamps=True,beam_size=1,vad_filter=True)
        json.dump([{'w':w.word.strip(),'s':round(w.start,2),'e':round(w.end,2)} for sg in segs for w in sg.words],open(wj,'w'))
    W=json.load(open(wj)); tw=[norm(x['w']) for x in W]
    quote=T[tid]['quotes'][qi]; qw=[norm(x) for x in quote.split()]; qw=[x for x in qw if x]; n=len(qw)
    best=(0,0,0)
    for i in range(len(tw)):
        for L in (n-2,n,n+2):
            r=difflib.SequenceMatcher(None,qw,tw[i:i+L],autojunk=False).ratio()
            if r>best[0]: best=(r,i,L)
    r,i,L=best; seg=W[i:i+L]
    # trim edges that don't match quote's first/last word
    st0=seg[0]['s']; en0=seg[-1]['e']; a=max(0,st0-PAD0); b=en0+PAD1
    clip=f'{OUT}/{tid}-q{qi}.mp4'
    subprocess.run(['ffmpeg','-y','-loglevel','error','-ss',f'{a:.2f}','-i',mp4,'-t',f'{b-a:.2f}','-vf','scale=-2:720','-c:v','libx264','-preset','slow','-crf','25','-pix_fmt','yuv420p','-c:a','aac','-b:a','96k','-movflags','+faststart',clip],check=True)
    out[f'{tid}:{qi}']={'talk':tid,'q':qi,'src':f'assets/clips/{tid}-q{qi}.mp4','dur':round(b-a,2),'speech':[round(st0-a,2),round(en0-a,2)],'match':round(r,3),
        'words':[{'w':x['w'],'s':round(x['s']-a,2),'e':round(x['e']-a,2)} for x in seg],'from':v,'at':round(a,2)}
    print(tid,qi,'match',round(r,3),'at',round(a,1),'dur',round(b-a,1),os.path.getsize(clip)//1024,'KB')
open(os.path.join(ROOT,'assets','clips.js'),'w').write('// GENERATED by tools/build_clips.py\nwindow.CLIPS = '+json.dumps(out,ensure_ascii=False,indent=1)+';\n')
