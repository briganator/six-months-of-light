"""Gather several official photos per speaker (different conferences, so different poses/angles)
from the speaker's ChurchofJesusChrist.org General Conference page. Each image is face-cropped
(images with no clear single face, e.g. artwork, are skipped), saved locally as
assets/speakers/opts/<speaker-slug>-<n>.webp (480px) and -sm (160px), and listed in assets/speaker-options.js.
Option 0 is always the photo from this conference's talk (assets/speakers/<talk_id>.webp).
Run: /workspace/.venv-cv/bin/python tools/fetch_speaker_options.py"""
import re, json, io, os, unicodedata, urllib.request, hashlib
import cv2, numpy as np
from PIL import Image
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__))); OUT=os.path.join(ROOT,'assets','speakers','opts'); os.makedirs(OUT,exist_ok=True)
UA={'User-Agent':'Mozilla/5.0'}; MAX=5
get=lambda u: urllib.request.urlopen(urllib.request.Request(u,headers=UA),timeout=30).read()
def slug(n):
    n=unicodedata.normalize('NFD',n); n=''.join(c for c in n if not unicodedata.combining(c)).lower()
    n=re.sub(r'^(elder|sister|president|bishop|brother)\s+','',n); return re.sub(r'[^a-z0-9]+','-',n).strip('-')
casc=cv2.CascadeClassifier(cv2.data.haarcascades+'haarcascade_frontalface_default.xml')
idx=json.load(open(os.path.join(ROOT,'assets','speakers','index.json')))['photos']
cur={}; 
for tid,v in idx.items(): cur.setdefault(slug(v['speaker']),[]).append(tid)
SLUG_FIX={'andrea-munoz-spannaus':'andrea-munoz-spannaus'}
res={}
for sp,tids in cur.items():
    opts=[{'src':f'assets/speakers/{tids[0]}.webp','sm':f'assets/speakers/{tids[0]}-sm.webp','label':'This conference'}]
    seen={hashlib.md5(open(os.path.join(ROOT,'assets','speakers',f'{tids[0]}.webp'),'rb').read()).hexdigest()}
    cur_ids=set()
    for t in tids: cur_ids.add(re.search(r'/imgs/([a-z0-9]+)/',idx[t]['image']).group(1))
    try: html=get(f'https://www.churchofjesuschrist.org/study/general-conference/speakers/{SLUG_FIX.get(sp,sp)}?lang=eng').decode('utf8','ignore')
    except Exception as e: print('NOPAGE',sp,e); res[sp]=opts; continue
    ids=[]; [ids.append(i) for i in re.findall(r'/imgs/([a-z0-9]+)/full/',html) if i not in ids and i not in cur_ids]
    for iid in ids:
        if len(opts)>=MAX: break
        try: im=Image.open(io.BytesIO(get(f'https://www.churchofjesuschrist.org/imgs/{iid}/full/%211600%2C/0/default'))).convert('RGB')
        except Exception: continue
        W,H=im.size; g=cv2.cvtColor(np.array(im),cv2.COLOR_RGB2GRAY)
        f=casc.detectMultiScale(g,1.1,6,minSize=(W//14,W//14))
        if len(f)!=1: continue
        x,y,w,h=f[0]; side=int(min(w*2.6,W,H)); cx=x+w/2; cy=y+h*.62
        L=int(max(0,min(W-side,cx-side/2))); T=int(max(0,min(H-side,cy-side/2))); c=im.crop((L,T,L+side,T+side))
        n=len(opts); a=f'{OUT}/{sp}-{n}.webp'; c.resize((480,480),Image.LANCZOS).save(a,quality=82); c.resize((160,160),Image.LANCZOS).save(f'{OUT}/{sp}-{n}-sm.webp',quality=80)
        opts.append({'src':f'assets/speakers/opts/{sp}-{n}.webp','sm':f'assets/speakers/opts/{sp}-{n}-sm.webp','label':'Earlier conference','from':f'https://www.churchofjesuschrist.org/imgs/{iid}/full/%211600%2C/0/default'})
    res[sp]=opts; print(sp,len(opts))
open(os.path.join(ROOT,'assets','speaker-options.js'),'w').write('// GENERATED by tools/fetch_speaker_options.py\nwindow.SPEAKER_OPTS = '+json.dumps(res,indent=1)+';\n')
